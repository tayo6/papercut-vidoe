'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const sandbox = { window: { __snip: { clamp: (v, a, b) => Math.max(a, Math.min(b, v)) } } };
vm.runInNewContext(fs.readFileSync('src/e_core.js', 'utf8'), sandbox);
const E = sandbox.window.__snip.E;
const clip = E.newClip('image', { dur: 5 });
let a = E.addKf(clip, 'x', 0);
assert.equal(a.t, 0);
assert.equal(a.v, 0);
E.updateKf(clip, 'x', 0, { v: -0.5, e: 'lin' });
E.addKf(clip, 'x', 2);
E.updateKf(clip, 'x', 1, { v: 0.5, e: 'hold' });
assert.equal(E.kfIndex(clip, 'x', 0), 0);
assert.equal(E.tfAt(clip, 1).x, 0);
assert.throws(() => E.updateKf(clip, 'x', 0, { t: 2 }), /already has a keyframe/);
const moved = E.updateKf(clip, 'x', 1, { t: 3 });
assert.equal(moved.t, 3);
assert.equal(JSON.stringify(clip.kf.x.map(k => k.t)), JSON.stringify([0, 3]));
assert.throws(() => E.updateKf(clip, 'x', 0, { v: 4 }), /outside the supported range/);
assert.throws(() => E.updateKf(clip, 'x', 0, { e: 'bounce' }), /Choose Smooth/);
assert.equal(E.deleteKf(clip, 'x', 0), true);
assert.equal(clip.kf.x.length, 1);
assert.equal(E.deleteKf(clip, 'x', 0), true);
assert.equal(clip.kf.x.length, 0);
assert.equal(clip.tf.x, 0.5);
assert.equal(E.deleteKf(clip, 'x', 0), false);

const animated = E.newClip('video', { dur: 5 });
E.addKf(animated, 'x', 0);
E.updateKf(animated, 'x', 0, { v: -0.4, e: { type: 'bezier', x1: 0.3, y1: 0.2, x2: 0.7, y2: 1.1 } });
E.addKf(animated, 'x', 1.5);
E.updateKf(animated, 'x', 1, { v: 0.4, e: 'lin' });
E.addKf(animated, 'o', 0);
E.updateKf(animated, 'o', 0, { v: 0.2 });
const saved = E.saveMotionPreset('Gentle drift', animated);
assert.equal(saved.name, 'Gentle drift');
assert.equal(saved.keyframes, 3);
assert.equal(E.listMotionPresets().length, 1);
const updated = E.saveMotionPreset('gentle drift', animated);
assert.equal(updated.id, saved.id);
assert.equal(E.listMotionPresets().length, 1);
const target = E.newClip('text', { dur: 5 });
assert.equal(E.applyMotionPreset(saved.id, target), true);
assert.notEqual(target.kf, animated.kf);
assert.equal(JSON.stringify(target.kf.x.map(k => k.t)), JSON.stringify([0, 1.5]));
assert.equal(target.kf.x[0].e.type, 'bezier');
assert.equal(target.kf.x[0].e.y2, 1.1);
target.kf.x[0].v = 0.9; target.kf.x[0].e.y2 = 0.9;
assert.equal(animated.kf.x[0].v, -0.4);
assert.equal(animated.kf.x[0].e.y2, 1.1);
const short = E.newClip('image', { dur: 1 });
assert.throws(() => E.applyMotionPreset(saved.id, short), /longer than the selected clip/);
assert.throws(() => E.saveMotionPreset('Audio motion', E.newClip('audio')), /image, video or text/);
assert.throws(() => E.saveMotionPreset('Empty', E.newClip('image')), /at least one keyframe/);
assert.equal(E.deleteMotionPreset(saved.id), true);
assert.equal(E.deleteMotionPreset(saved.id), false);
console.log('Visual keyframe editing and motion preset tests passed.');

const bezierClip = E.newClip('image', { dur: 4 });
E.addKf(bezierClip, 'x', 0);
E.addKf(bezierClip, 'x', 2);
E.updateKf(bezierClip, 'x', 0, { v: 0, e: { type: 'bezier', x1: 0.25, y1: 0.1, x2: 0.25, y2: 1 } });
E.updateKf(bezierClip, 'x', 1, { v: 1 });
assert(Math.abs(E.tfAt(bezierClip, 1).x - 0.8024024) < 1e-5);
assert.throws(() => E.updateKf(bezierClip, 'x', 0, { e: { type: 'bezier', x1: 1.2, y1: 0, x2: 0.2, y2: 1 } }), /Bezier X control points/);
assert.throws(() => E.updateKf(bezierClip, 'x', 0, { e: { type: 'bezier', x1: 0.2, y1: 2, x2: 0.8, y2: 1 } }), /Bezier Y control points/);
const splitSource = E.newClip('image', { dur: 4 });
E.proj.clips.push(splitSource);
E.addKf(splitSource, 's', 0);
E.updateKf(splitSource, 's', 0, { v: 0.6, e: { type: 'bezier', x1: 0.3, y1: 0.2, x2: 0.7, y2: 1.1 } });
E.addKf(splitSource, 's', 2);
const splitRight = E.splitClip(splitSource.id, 1);
assert.equal(splitRight.kf.s[0].e.type, 'bezier');
assert.equal(splitRight.kf.s[0].e.y2, 1.1);
assert.notEqual(splitRight.kf.s[0].e, splitSource.kf.s[0].e);
splitRight.kf.s[0].e.y2 = 0.9;
assert.equal(splitSource.kf.s[0].e.y2, 1.1);

console.log('Per-keyframe Bezier easing tests passed.');

const laneClip = E.newClip('image', { dur: 6 });
E.addKf(laneClip, 'x', 0);
E.addKf(laneClip, 'x', 3);
E.addKf(laneClip, 'y', 0);
assert.equal(E.movePropertyKfTime(laneClip, 'x', 0, 1.25), 1.25);
assert.equal(JSON.stringify(laneClip.kf.x.map(k => k.t)), JSON.stringify([1.25, 3]));
assert.equal(JSON.stringify(laneClip.kf.y.map(k => k.t)), JSON.stringify([0]));
assert.equal(JSON.stringify(E.kfTimes(laneClip)), JSON.stringify([0, 1.25, 3]));
assert.equal(E.movePropertyKfTime(laneClip, 'x', 1.25, 3), 1.25);
assert.equal(E.movePropertyKfTime(laneClip, 'x', 1.25, 99), 6);
assert.equal(E.movePropertyKfTime(laneClip, 'y', 4, 2), 4);
assert.equal(E.movePropertyKfTime(laneClip, 'rotation', 0, 1), 0);
assert.equal(JSON.stringify(laneClip.kf.x.map(k => k.t)), JSON.stringify([3, 6]));

console.log('Independent property keyframe drag tests passed.');
